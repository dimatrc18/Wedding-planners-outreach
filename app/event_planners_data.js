export function loadStoredEventPartners() {
  if (typeof localStorage === 'undefined') return INITIAL_EVENT_PARTNERS;
  try {
    const raw = localStorage.getItem(EVENT_STORAGE_KEY);
    if (!raw) return INITIAL_EVENT_PARTNERS;
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed) || parsed.length === 0) return INITIAL_EVENT_PARTNERS;
    return mergeEventRecords(INITIAL_EVENT_PARTNERS, parsed);
  } catch (_) {
    return INITIAL_EVENT_PARTNERS;
  }
}

export function saveStoredEventPartners(partners) {
  if (typeof localStorage === 'undefined' || !Array.isArray(partners)) return;
  try {
    localStorage.setItem(EVENT_STORAGE_KEY, JSON.stringify(partners));
  } catch (_) {}
}

export function mergeEventRecords(initial, saved) {
  const map = new Map();
  for (const s of saved) {
    if (s && s.id) map.set(s.id, s);
  }
  return initial.map((init) => {
    const override = map.get(init.id);
    return override ? { ...init, ...override } : init;
  });
}

